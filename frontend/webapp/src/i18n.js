const KEY = 'itsm_lang';
const getLang = () => (typeof localStorage !== 'undefined' && localStorage.getItem(KEY)) || 'fr';

export function setLang(lang) {
  if (typeof localStorage !== 'undefined') localStorage.setItem(KEY, lang);
  if (typeof document !== 'undefined') document.documentElement.lang = lang;
}

// Hook: renvoie { t, lang, setLang }
export function useI18n() {
  const [lang, setL] = useState(getLang());
  useEffect(() => { document.documentElement.lang = lang; }, [lang]);
  const t = (k) => (DICT[lang] && DICT[lang][k]) || (DICT.fr[k]) || k;
  const change = (l) => { setLang(l); setL(l); };
  return { t, lang, setLang: change };
}

